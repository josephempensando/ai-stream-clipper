import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { chromium } from '@playwright/test';
import { createApp } from '../src/server/app.js';
import type { ClipEdit, RenderOptions } from '../src/shared/types.js';
import { config } from '../src/server/config.js';

const root = process.argv[2];
if (!root) throw new Error('Usage: npx tsx scripts/check-retention-ui.ts <successful smoke-retention artifact directory>');
const { app, store } = await createApp(path.resolve(root));
const job = [...store.jobs.values()].find(j => j.status === 'complete' && j.highlights.some(h => h.retention));
assert.ok(job, 'Run smoke-retention first to create a complete authorized sample.');
const server = app.listen(0, '127.0.0.1'); await new Promise<void>(resolve => server.once('listening', resolve));
const address = server.address(); assert.ok(address && typeof address !== 'string');
config.port = address.port;
const edge = 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe';
const browser = await chromium.launch({ headless: true, ...(existsSync(edge) ? { executablePath: edge } : {}) });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } }); const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(`http://127.0.0.1:${address.port}`);
  await page.getByRole('button', { name: /Recordings/ }).click();
  await page.getByRole('button', { name: new RegExp(job.name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')) }).click();
  const editor = page.getByRole('region', { name: 'AI Retention Editor' });
  await editor.getByText(/Model assessment:/).waitFor();
  const previews = editor.locator('video'); assert.equal(await previews.count(), 2);
  await page.waitForFunction(() => [...document.querySelectorAll<HTMLVideoElement>('.retention-previews video')].every(v => v.readyState >= 1 && Number.isFinite(v.duration)));
  assert.ok(await previews.nth(1).evaluate((v: HTMLVideoElement) => v.videoWidth === 1080 && v.videoHeight === 1920));
  await editor.getByText('Exact edit decisions & recommendations', { exact: true }).click();
  assert.ok(await editor.locator('tbody tr').count() > 0);
  await editor.getByText('Correct subtitles in this preview', { exact: true }).click();
  const correction = editor.getByRole('textbox', { name: /^Caption at / }).first();
  const original = await correction.inputValue(); await correction.fill(original.toUpperCase());
  await editor.getByLabel('Pattern interrupts for this clip', { exact: true }).uncheck();
  await editor.getByLabel('Clip ending', { exact: true }).selectOption('natural');
  await editor.getByLabel('Frame rate', { exact: true }).selectOption('60');
  let body: { clips: ClipEdit[]; options: RenderOptions } | undefined;
  await page.route(`**/api/jobs/${job.id}/render`, async route => { body = route.request().postDataJSON(); await route.fulfill({ json: job }); });
  const request = page.waitForRequest(`**/api/jobs/${job.id}/render`);
  await editor.getByRole('button', { name: 'Export selected', exact: true }).click(); await request;
  assert.equal(body?.options.retention?.fps, 60);
  assert.equal(body?.clips[0]?.adjustments?.patternInterrupts, false);
  assert.equal(body?.clips[0]?.adjustments?.ending, 'natural');
  assert.equal(body?.clips[0]?.adjustments?.captions[0]?.text, original.toUpperCase());
  await page.screenshot({ path: path.join(root, 'retention-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: path.join(root, 'retention-mobile.png'), fullPage: true });
  assert.deepEqual(errors, []);
  console.log('Retention browser checks passed: actual source/export video metadata, narrative/EDL, caption correction, clip overrides, export payload and mobile layout. Export request used an explicit test double.');
} finally { await browser.close(); server.closeAllConnections(); server.close(); }
