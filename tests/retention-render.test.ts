test('owned sample: real retention render cuts silence, burns karaoke and encodes synchronized 60 FPS H.264/AAC', { timeout: 180000 }, async () => {
  const dir = path.resolve('test-artifacts', `retention-${randomUUID()}`); await mkdir(dir, { recursive: true });
  const source = path.join(dir, 'owned.mp4');
  await ffmpeg(['-f', 'lavfi', '-i', 'testsrc2=s=320x180:r=60:d=5', '-f', 'lavfi', '-i', 'sine=frequency=440:sample_rate=48000:duration=5', '-c:v', 'libx264', '-preset', 'ultrafast', '-c:a', 'aac', '-t', '5', source]);
  const h: Highlight = { id: 'owned', start: 0, end: 5, score: 80, title: 'Generated sample', explanation: 'Test only.', evidence: [], frameTimes: [], heuristicScore: 0, transcript: 'Why? Fixed!', cues: [
    { start: 0, end: 1, text: 'Why?', words: [{ start: 0, end: 1, word: 'Why?' }] },
    { start: 3, end: 5, text: 'Fixed!', words: [{ start: 3, end: 5, word: 'Fixed!' }] },
  ] };
  const settings = retentionSettingsSchema.parse({ autoEdit: true, fps: 60, ending: 'cta', cta: 'What would you check?' });
  const n = validateNarrative({ hook: { first: 0, last: 0 }, setup: null, escalation: null, payoff: { first: 1, last: 1 }, ending: { first: 1, last: 1 }, reason: 'Question then resolution.', loop: false, loopReason: 'No coherent loop.', emphasis: [1], pauseCuts: [0] }, h);
  const edl = buildEdl(h, n, [], settings);
  const percentages: number[] = [];
  await renderRetention(source, dir, 'clip-01', h, edl, { layout: 'blur', cropX: 0.5, subtitles: true, retention: settings }, { segments: h.cues!, model: 'test-fixture', language: 'en' }, [], [], async p => { percentages.push(p); });
  const output = path.join(dir, 'clip-01.mp4'); const media = await probe(output);
  assert.equal(media.width, 1080); assert.equal(media.height, 1920); assert.equal(media.hasAudio, true);
  assert.ok(Math.abs(media.duration - 3.5) < 0.15);
  const streams = JSON.parse(await runProcess(config.ffprobe, ['-v', 'error', '-show_streams', '-of', 'json', output])).streams as { codec_name: string; codec_type: string; r_frame_rate: string; duration: string; start_time: string }[];
  assert.equal(streams.find(s => s.codec_type === 'video')?.codec_name, 'h264');
  assert.equal(streams.find(s => s.codec_type === 'video')?.r_frame_rate, '60/1');
  assert.equal(streams.find(s => s.codec_type === 'audio')?.codec_name, 'aac');
  assert.ok(streams.every(s => Math.abs(Number(s.start_time)) < 0.08));
  assert.ok(Math.abs(Number(streams[0]?.duration) - Number(streams[1]?.duration)) < 0.15);
  assert.match(await readFile(path.join(dir, 'clip-01.ass'), 'utf8'), /\\kf100/);
  await ffmpeg(['-i', output, '-v', 'error', '-f', 'null', '-']);
  assert.ok(percentages.some(p => p < 100), 'FFmpeg must emit actual intermediate progress.');
  const musicId = randomUUID(); const sfxId = randomUUID();
  const musicFile = path.join(dir, 'owned-music.wav'); const sfxFile = path.join(dir, 'owned-effect.wav');
  await ffmpeg(['-f', 'lavfi', '-i', 'sine=frequency=900:sample_rate=48000:duration=1', musicFile]);
  await ffmpeg(['-f', 'lavfi', '-i', 'sine=frequency=1400:sample_rate=48000:duration=0.2', sfxFile]);
  const mixed = { ...settings, fps: 30 as const, ending: 'loop' as const, musicId, sfxId };
  const loopEdl = buildEdl(h, { ...n, loop: true, loopReason: 'Explicit test fixture allowing visual blend.' }, [], mixed);
  assert.ok(loopEdl.actions.some(a => a.type === 'sfx'));
  await renderRetention(source, dir, 'clip-mix-loop', h, loopEdl, { layout: 'crop', cropX: 0.5, subtitles: true, retention: mixed }, { segments: h.cues!, model: 'test-fixture', language: 'en' }, [
    { id: musicId, kind: 'music', file: musicFile, name: 'Owned generated tone', provenance: 'Generated by this test with FFmpeg.', license: 'owned', permission: true, addedAt: new Date().toISOString() },
    { id: sfxId, kind: 'sfx', file: sfxFile, name: 'Owned generated effect', provenance: 'Generated by this test with FFmpeg.', license: 'owned', permission: true, addedAt: new Date().toISOString() },
  ], [{ start: 3, end: 5, text: 'Fixed.' }], async () => {});
  const mixedOutput = path.join(dir, 'clip-mix-loop.mp4');
  assert.ok(Math.abs((await probe(mixedOutput)).duration - 3.5) < 0.15);
  assert.match(await readFile(path.join(dir, 'clip-mix-loop.srt'), 'utf8'), /Fixed\./);
  await ffmpeg(['-i', mixedOutput, '-v', 'error', '-f', 'null', '-']);
  const editedDir = path.join(dir, 'edited');
  const job: Job = { id: randomUUID(), name: 'Owned sample', status: 'review', stage: 'Ready', progress: 100, createdAt: new Date().toISOString(), source: 'upload', vodId: null, vodOffset: 0, mediaHash: 'owned-test-fixture', media: { duration: 5, width: 320, height: 180, hasAudio: true }, highlights: [{ ...h, retention: { narrative: n, edl } }], outputs: [], warnings: [], error: null, renderOptions: null };
  await renderClips(job, source, editedDir, [{ id: h.id, start: 0, end: 4 }], { layout: 'crop', cropX: 0.5, subtitles: true, retention: { ...settings, autoEdit: false, ending: 'natural' } }, { segments: h.cues!, model: 'test-fixture', language: 'en' }, async () => {});
  const manifest = JSON.parse(await readFile(path.join(editedDir, 'results.json'), 'utf8'));
  assert.equal(manifest.highlights[0].retention, undefined, 'Changed source boundaries must not export stale narrative timestamps.');
  console.log(`Owned synthetic render validated at ${output}; model output is an explicit fixture, not live inference.`);
});

test('many fractional-frame cuts preserve the final audio event and caption timeline', { timeout: 120000 }, async () => {
  const dir = path.resolve('test-artifacts', `retention-fractional-${randomUUID()}`); await mkdir(dir, { recursive: true });
  const source = path.join(dir, 'owned-timing.mp4');
  await ffmpeg(['-f', 'lavfi', '-i', 'testsrc2=s=320x180:r=30:d=4', '-f', 'lavfi', '-i', 'aevalsrc=0.5*sin(2*PI*if(gte(t\\,3.8)\\,1400\\,440)*t):s=48000:d=4', '-c:v', 'libx264', '-preset', 'ultrafast', '-c:a', 'aac', source]);
  const keep = Array.from({ length: 20 }, (_, i) => ({ start: i * 0.2, end: i * 0.2 + 0.19 }));
  const edl: RetentionEdl = { version: 1, sourceStart: 0, sourceEnd: 4, duration: 3.8, keep, actions: [], recommendations: [] };
  const settings = retentionSettingsSchema.parse({ captions: { enabled: false }, normalize: false });
  const h: Highlight = { id: 'timing', start: 0, end: 4, title: 'Owned audio marker', score: 0, explanation: 'Timing fixture.', evidence: [], transcript: '', frameTimes: [], heuristicScore: 0 };
  await renderRetention(source, dir, 'timing', h, edl, { layout: 'crop', cropX: 0.5, subtitles: false, retention: settings }, { segments: [], model: 'fixture', language: 'en' }, [], [], async () => {});
  const pcm = path.join(dir, 'final-marker.f32');
  await ffmpeg(['-i', path.join(dir, 'timing.mp4'), '-ss', '3.66', '-t', '0.1', '-vn', '-af', 'bandpass=f=1400:width_type=h:w=200', '-ac', '1', '-ar', '48000', '-f', 'f32le', pcm]);
  const bytes = await readFile(pcm); let sum = 0;
  for (let i = 0; i + 4 <= bytes.length; i += 4) sum += bytes.readFloatLE(i) ** 2;
  const rms = Math.sqrt(sum / (bytes.length / 4));
  assert.ok(rms > 0.05, `Final source audio marker must survive at its mapped time (RMS ${rms}).`);
});
